export const DotMatrixDisplay: React.FC<DotMatrixDisplayProps> = ({
  text,
  className = '',
  activeColor = '#34d399', // Emerald 400
  inactiveColor = '#064e3b22', // Dim background dot
  size = 'md',
}) => {
  const dotSizeClass =
    size === 'sm' ? 'w-0.5 h-0.5 gap-[1px]' : size === 'lg' ? 'w-1.5 h-1.5 gap-[2px]' : 'w-1 h-1 gap-[1px]';

  const uppercaseText = text.toUpperCase();

  return (
    <div className={`inline-flex items-center gap-1.5 bg-black/90 p-1.5 rounded-md border border-emerald-950 shadow-inner ${className}`}>
      {uppercaseText.split('').map((char, charIdx) => {
        const matrix = CHAR_MAP[char] || CHAR_MAP[' '];

        return (
          <div key={charIdx} className={`grid grid-cols-5 ${dotSizeClass}`}>
            {matrix.map((rowByte, rowIdx) =>
              Array.from({ length: 5 }).map((_, colIdx) => {
                const isBitSet = (rowByte & (0x80 >> colIdx)) !== 0;
                return (
                  <span
                    key={`${rowIdx}-${colIdx}`}
                    className="rounded-[0.5px] transition-colors"
                    style={{
                      backgroundColor: isBitSet ? activeColor : inactiveColor,
                      boxShadow: isBitSet ? `0 0 3px ${activeColor}` : 'none',
                    }}
                  />
                );
              })
            )}
          </div>
        );
      })}
    </div>
  );
};
